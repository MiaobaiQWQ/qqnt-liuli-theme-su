param(
    [switch]$NoCompile
)

$ErrorActionPreference = 'Stop'
$psDir = $PSScriptRoot
$dist = [IO.Path]::GetFullPath((Join-Path $psDir '..\dist'))
if (-not (Test-Path $dist)) { New-Item -ItemType Directory -Force -Path $dist | Out-Null }

$installPath = Join-Path $psDir 'install.ps1'
$loaderPath = Join-Path $psDir 'liteloader.ps1'
$payloadPath = Join-Path $psDir 'payload.zip'
$corePath = Join-Path $psDir 'lite-loader.zip'
foreach ($p in @($installPath, $loaderPath, $payloadPath, $corePath)) {
    if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { throw "缺少 $p" }
}

$install = [IO.File]::ReadAllText($installPath, [Text.Encoding]::UTF8)
$loader = [IO.File]::ReadAllText($loaderPath, [Text.Encoding]::UTF8)
$install = $install.Replace(". (Join-Path `$PSScriptRoot 'liteloader.ps1')", '')
$install = $install.Replace("Join-Path `$PSScriptRoot 'payload.zip'", "if (`$script:RuntimeDir) { Join-Path `$script:RuntimeDir 'payload.zip' } else { '' }")
$install = $install.Replace("Join-Path `$PSScriptRoot 'lite-loader.zip'", "if (`$script:RuntimeDir) { Join-Path `$script:RuntimeDir 'lite-loader.zip' } else { '' }")

$payloadB64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($payloadPath))
$coreB64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($corePath))
function Wrap-B64([string]$s) {
    $sb = New-Object Text.StringBuilder
    for ($i = 0; $i -lt $s.Length; $i += 120) {
        [void]$sb.AppendLine($s.Substring($i, [Math]::Min(120, $s.Length - $i)))
    }
    return $sb.ToString().TrimEnd()
}

$embedLines = @(
    '',
    '# ---- embedded payload (generated by build) ----',
    "`$script:RuntimeDir = ''",
    "`$script:PayloadB64 = @'",
    (Wrap-B64 $payloadB64),
    "'@",
    "`$script:CoreB64 = @'",
    (Wrap-B64 $coreB64),
    "'@",
    "`$script:PayloadBytes = [Convert]::FromBase64String(`$script:PayloadB64)",
    "`$script:CoreBytes = [Convert]::FromBase64String(`$script:CoreB64)",
    ''
)
$embed = $embedLines -join "`n"

$anchor = "`$ErrorActionPreference = 'Stop'"
$idx = $install.IndexOf($anchor)
if ($idx -lt 0) { throw 'install.ps1 里找不到 ErrorActionPreference 锚点' }
$install = $install.Substring(0, $idx) + $embed + "`n" + $install.Substring($idx)

$anchor2 = "`$script:Progress = `$null"
$idx2 = $install.IndexOf($anchor2)
if ($idx2 -lt 0) { throw 'install.ps1 里找不到 Progress 锚点' }
$insertAt = $idx2 + $anchor2.Length
$install = $install.Substring(0, $insertAt) + "`n`n" + $loader + "`n" + $install.Substring($insertAt)

$merged = Join-Path $psDir 'merged-install.ps1'
[IO.File]::WriteAllText($merged, $install, (New-Object Text.UTF8Encoding($true)))
Write-Host ("merged: {0:N0} chars" -f $install.Length)

if ($NoCompile) { return }

$compile = Join-Path $psDir 'compile-ps2exe.ps1'
$out = Join-Path $dist 'LiuliThemeInstaller.exe'
if (Test-Path -LiteralPath $out) { Remove-Item -LiteralPath $out -Force }
powershell -NoProfile -ExecutionPolicy Bypass -File $compile -Merged $merged -Out $out 2>&1 | Out-String
if (-not (Test-Path -LiteralPath $out)) { throw 'PS2EXE 未生成 exe' }
$final = Join-Path $dist '琉璃主题安装器.exe'
Copy-Item -LiteralPath $out -Destination $final -Force
Remove-Item -LiteralPath $out -Force
Write-Host ("EXE: {0} ({1:N0} bytes)" -f $final, (Get-Item $final).Length)

